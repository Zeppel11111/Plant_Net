#ifndef     APP_MSG_H
#define     APP_MSG_H

#include    <stdint.h>

/* =====================================================================
 * App 层任务间消息定义（层间契约）
 * 采集任务 → [队列] → 上行任务
 * ===================================================================== */

/* 一条传感器采样（与服务器行契约一致：温度x10, 湿度x10, 光照） */
typedef struct
{
    int16_t  temp_x10;    /* 温度 ×10，如 254 = 25.4℃ */
    int16_t  humi_x10;    /* 湿度 ×10 */
    uint32_t lux;         /* 光照 LUX */
    uint32_t seq;         /* 序号：便于观察丢帧/积压 */
} sensor_msg_t;

/* 队列深度：满则丢最旧（采样数据，滞后数据无意义） */
#define     APP_SENSOR_QUEUE_DEPTH   4

#endif
